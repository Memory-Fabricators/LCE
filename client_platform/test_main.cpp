#include "client_platform.h"
#include <cassert>
#include <cstdio>
#include <cstdint>

int main()
{
    // PNG decoding via zune-png, exposed through client_platform.
    static const uint8_t kPngData[] = {
        0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, 0x00, 0x00, 0x00, 0x0d, 0x49, 0x48, 0x44, 0x52,
        0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01, 0x08, 0x06, 0x00, 0x00, 0x00, 0x1f, 0x15, 0xc4,
        0x89, 0x00, 0x00, 0x00, 0x0d, 0x49, 0x44, 0x41, 0x54, 0x78, 0x9c, 0x63, 0xf8, 0xcf, 0xc0, 0xf0,
        0x1f, 0x00, 0x05, 0x00, 0x01, 0xff, 0x89, 0x99, 0x3d, 0x1d, 0x00, 0x00, 0x00, 0x00, 0x49, 0x45,
        0x4e, 0x44, 0xae, 0x42, 0x60, 0x82
    };
    DecodedImage decoded = {};
    bool decode_res = angle_wgpu_decode_png_memory(kPngData, sizeof(kPngData), &decoded);
    assert(decode_res);
    assert(decoded.width == 1);
    assert(decoded.height == 1);
    assert(decoded.pixels != nullptr);
    // ARGB: 0xFFFF0000 for red pixel (A=255, R=255, G=0, B=0)
    assert(decoded.pixels[0] == 0xFFFF0000);
    printf("[Test] PNG decoded successfully: %dx%d pixel 0x%08X\n", decoded.width, decoded.height, decoded.pixels[0]);
    angle_wgpu_free_decoded_image(&decoded);
    assert(decoded.pixels == nullptr);

    printf("[Test] All client_platform tests passed successfully!\n");
    return 0;
}
